class Activity {
  final String title;
  final String date;
  final String location;
  final String image;
  final String time;
  final int capacity;
  final int participantCount;

  Activity({
    required this.title,
    required this.date,
    required this.location,
    required this.image,
    required this.time,
    required this.capacity,
    required this.participantCount,
  });
}
